  /** mapRect(state) → visible map rectangle inside U after panels/columns/insets (MAP-02 §6). */
  layout.mapRect = function (state) {
    state = state || App.state;
    var U = state.layout.U, mode = state.layout.mode;
    var top = 0, right = 0, bottom = 0, left = 0;
    if (mode === 'narrow') {
      bottom = state.search.active ? U.h : (state.sheet.height || 0);
    } else {
      var c = layout.columns(state);
      top = c.topbarH; left = c.leftW; right = c.detailW;
    }
    Object.keys(_insets).forEach(function (k) {
      var r = _insets[k]; top = Math.max(top, r.top || 0); right = Math.max(right, r.right || 0);
      bottom = Math.max(bottom, r.bottom || 0); left = Math.max(left, r.left || 0);
    });
    var h = Math.max(0, U.h - top - bottom), w = Math.max(0, U.w - left - right);
    // LAY-04 (containers coreRequest #2): a map band too short to carry its own
    // attribution is a tile sliver, which the rule forbids. Two owners can each
    // publish a legal inset and still add up to one, so clamp here where both are
    // visible: first try to give the band its 44px back from the top inset, and if
    // the screen truly cannot afford it, drop the band to zero instead of a sliver.
    var MIN_BAND = 44;
    if (mode === 'narrow' && h > 0 && h < MIN_BAND) {
      var give = Math.min(top, MIN_BAND - h);
      top -= give; h += give;
      if (h < MIN_BAND) { h = 0; w = 0; }
    }
    return { x: U.x + left, y: U.y + top, w: w, h: h };
  };

