    if (typeof opts.seed === 'function') s = opts.seed(s) || s;   // adapter: prefs + user state
    App.state = s;
    layout.derive(App.state, new Set(['*']));
    // init modules in fixed order
    App.MODULE_ORDER.forEach(function (name) {
      var mod = App.modules[name];
      if (!mod) { console.warn('[boot] module missing: ' + name); return; }
      try { if (typeof mod.init === 'function') mod.init(App.ctx()); } catch (e) { console.error('[init:' + name + ']', e); }
    });
    layout.bind();
    nav.bind();
    _pendingChanged.add('*');
    flushRender();
    layout.schedule();                       // second measure once module CSS is in place; fires layout:settled
