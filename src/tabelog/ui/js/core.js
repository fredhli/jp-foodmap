  /** I18N.register({en:{'简体':'English'}, ja:{...}, tw:{...}}) — merges. */
  I18N.register = function (tables) {
    if (!tables) return;
    Object.keys(tables).forEach(function (lang) {
      if (!_tables[lang]) _tables[lang] = {};
      var src = tables[lang] || {};
      Object.keys(src).forEach(function (k) {
        _tables[lang][k] = src[k];
        _zhKeys.add(k);
      });
    });
  };
  /** I18N.keys() → every registered zh key (for the OpenCC tw pass). */
  I18N.keys = function () { return Array.from(_zhKeys).sort(); };
  I18N.tables = function () { return _tables; };
  I18N.lang = function () { return App.state ? App.state.lang : 'zh'; };

  function interpolate(s, params) {
    if (!params) return s;
    return s.replace(/\{(\w+)\}/g, function (m, k) {
      return params[k] === undefined || params[k] === null ? m : String(params[k]);
    });
  }

  /**
   * t(zhKey, params) — the only rendering entry for UI copy. Keys are the
   * Simplified Chinese strings; a missing translation falls back to zh.
   * Params fill {name} placeholders; never concatenate sentences.
   */
  var t = window.t = function (key, params) {
    var lang = I18N.lang();
    _zhKeys.add(key);
    var table = _tables[lang];
    var s;
    if (lang !== 'zh' && table && table[key] !== undefined) s = table[key];
    else if (lang !== 'zh' && window.Business && typeof window.Business.localizeText === 'function') s = window.Business.localizeText(key);
    else s = key;
    return interpolate(String(s), params);
  };
  I18N.t = t;

