  var BOOT_TIMEOUT_MS = 9000;
  var bootPending = false;
  function boot() {
    // M-022: 加载中… / 加载失败 used to land in .ff-total, which was the FAB's
    // second number. The FAB now shows 命中 / 视野内 and .ff-total only lives
    // inside the (closed) filter sheet, so the status has to reach .ff-inview
    // too or boot progress becomes invisible.
    function setTotals(text) {
      hook('onBootStatus', text);   // [4.0 seam] was .ff-total / .ff-inview
    }
    if (bootPending) return;          // double-tap on 重试
    bootPending = true;
    hideBootFailure();
    setTotals(localizeText('加载中…'));
    var ctrl = (typeof AbortController !== 'undefined') ? new AbortController() : null;
    var timedOut = false;
    var timer = setTimeout(function() {
      timedOut = true;
      if (ctrl) ctrl.abort();
    }, BOOT_TIMEOUT_MS);
    fetch('data/restaurants.json',
          {cache: 'force-cache', signal: ctrl && ctrl.signal})
      .then(function(r) {
        if (!r.ok) throw new Error('HTTP ' + r.status);
        return r.json();
      })
      .then(function(data) {
        clearTimeout(timer);
        bootPending = false;
        // M-054: an exception out of initMap is an initialisation bug, not
        // a network failure — saying "check your network" about it (and
        // offering a retry that re-downloads 3MB to hit the same bug) sent
        // people chasing the wrong problem.
        try {
          B.init(data, hooks);   // [4.0 seam] was initMap(data)
          hook('onData', data);
        } catch (e) {
          console.error('[tabelog] map initialisation failed:', e);
          setTotals(localizeText('初始化失败'));
          showBootFailure('deps', function() { location.reload(); });
        }
      })
      .catch(function(e) {
        clearTimeout(timer);
        bootPending = false;
        console.error('[tabelog] restaurants.json load failed' +
                      (timedOut ? ' (timeout)' : '') + ':', e);
        setTotals(localizeText('加载失败'));
        // M-075 / M-168: visible, announced, and retryable in place — the
        // old handler wrote "加载失败" into a counter inside a drawer that
        // is collapsed by default.
        showBootFailure('data', boot);
      });
  }
  // [4.0 seam] boot() no longer self-starts at DOMContentLoaded; the adapter
  // calls Business.boot(hooks) once core, modules and folium's map exist.
  B.boot = function(h) { hooks = h || hooks; boot(); };
